public class Operadores {
    public static void main(String[] args) {
        int inota = 3;
        float fnota = 3f;
        double dnota = 3.0;

        int inotaFinal = inota * 10 / 4;
        float fnotaFinal = fnota * 10f / 4f;
        double dnotaFinal = dnota * 10.0 / 4.0;

        System.out.println("Nota Final (int): " + inotaFinal);
        System.out.println("Nota Final (float): " + fnotaFinal);
        System.out.println("Nota Final (double): " + dnotaFinal);
    }
}
